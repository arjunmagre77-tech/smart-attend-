// app/api/attendance/simulate/route.ts
// DEVELOPMENT ONLY — Simulates an RFID scan so you can test the dashboard before
// the physical ESP32 hardware is available.
//
// This route is DISABLED in production (NODE_ENV === "production").
// Simulated scans use source:"demo" and deviceId:"sim-device-dev".
//
// Usage:
//   POST /api/attendance/simulate
//   Body: { "rfidUid": "A31F2B09" }     ← use a UID from demo data or a real registered student
//   No auth headers required (uses the demo device credentials internally)

import { NextRequest, NextResponse } from "next/server";
import { z } from "zod";

const simulateSchema = z.object({
  // Accept any hex-looking UID so you can test unknown-card paths too
  rfidUid: z
    .string()
    .min(4)
    .max(32)
    .regex(/^[A-Fa-f0-9]+$/, "RFID UID must be hexadecimal"),
});

export async function POST(req: NextRequest) {
  // ── 0. Hard-block in production ───────────────────────────
  if (process.env.NODE_ENV === "production") {
    return NextResponse.json(
      {
        success: false,
        message:
          "Simulation endpoint is disabled in production. Use a real ESP32 device.",
      },
      { status: 403 }
    );
  }

  // ── 1. Parse body ─────────────────────────────────────────
  let body: unknown;
  try {
    body = await req.json();
  } catch {
    return NextResponse.json(
      { success: false, message: "Invalid JSON body" },
      { status: 400 }
    );
  }

  const parsed = simulateSchema.safeParse(body);
  if (!parsed.success) {
    return NextResponse.json(
      {
        success: false,
        message: "Invalid request body",
        errors: parsed.error.flatten().fieldErrors,
      },
      { status: 400 }
    );
  }

  const { rfidUid } = parsed.data;

  // ── 2. Build a synthetic scan payload ────────────────────
  const eventId = `sim_${rfidUid}_${Date.now()}`;
  const scanPayload = {
    rfidUid: rfidUid.toUpperCase(),
    // Use demo-device so session.ts accepts it without Firestore lookup in dev/demo mode.
    // When Firebase Admin is configured, ensure "demo-device" exists in Firestore → devices,
    // or set SIMULATE_DEVICE_ID + SIMULATE_DEVICE_SECRET to match a registered device.
    deviceId: process.env.SIMULATE_DEVICE_ID ?? "demo-device",
    eventId,
  };

  // ── 3. Forward to the real scan endpoint ─────────────────
  // Build the internal URL so we exercise the exact same validation and
  // Firestore write path as a real ESP32 scan.
  const origin = req.nextUrl.origin;
  const scanUrl = `${origin}/api/attendance/scan`;

  const deviceSecret =
    process.env.SIMULATE_DEVICE_SECRET ??
    process.env.DEMO_DEVICE_SECRET ??
    "demo-secret-key-for-testing";

  const scanRes = await fetch(scanUrl, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-Device-ID": process.env.SIMULATE_DEVICE_ID ?? "demo-device",
      "X-Device-Secret": deviceSecret,
      // Marker so logs can distinguish simulated vs real scans
      "X-Simulated": "1",
    },
    body: JSON.stringify(scanPayload),
  });

  const scanData = await scanRes.json();

  return NextResponse.json(
    {
      ...scanData,
      _simulated: true,
      _rfidUid: rfidUid.toUpperCase(),
      _eventId: eventId,
      _note:
        "This was a simulated scan generated by /api/attendance/simulate (dev only).",
    },
    { status: scanRes.status }
  );
}

// Provide a helpful GET response so developers can discover the endpoint
export async function GET() {
  if (process.env.NODE_ENV === "production") {
    return NextResponse.json({ error: "Not found" }, { status: 404 });
  }

  return NextResponse.json({
    endpoint: "POST /api/attendance/simulate",
    description: "Development-only RFID scan simulator. Disabled in production.",
    body: {
      rfidUid: "Hex string, 4-32 chars (e.g. A31F2B09 from demo data)",
    },
    demoRfidUids: [
      "A31F2B09 → Aryan Mehta",
      "B44C1D3A → Priya Sharma",
      "C55D2E4B → Rohan Patel",
      "D66E3F5C → Dev Kumar",
      "G99H6I8F → Aarav Verma",
    ],
    note: "Records appear instantly on the teacher dashboard via the Firestore real-time listener.",
  });
}
